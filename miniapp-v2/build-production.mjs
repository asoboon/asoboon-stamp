// Dependency-free bundling: preserve source order, CSS cascade and IIFE boundaries.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, relative } from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const dir='miniapp-v2/production';
const read=p=>readFileSync(resolve(root,p),'utf8');
const sources=JSON.parse(read(`${dir}/bundle-sources.json`));
const hash=s=>createHash('sha256').update(s).digest('hex').slice(0,12);
const envHash=p=>hash(read(p).trim());
const check=process.argv.includes('--check');
function output(path,text){
  if(check){
    const existing=read(path);
    if(existing!==text){
      let first=0;while(first<existing.length&&first<text.length&&existing[first]===text[first])first++;
      throw Error(`Stale production build: ${path}. expectedChars=${text.length} actualChars=${existing.length} firstDiff=${first} expected=${JSON.stringify(text.slice(first,first+40))} actual=${JSON.stringify(existing.slice(first,first+40))}. Run node miniapp-v2/build-production.mjs`);
    }
  }
  else writeFileSync(resolve(root,path),text);
}
function browserSource(p){
  let text=read(p);
  if(p==='miniapp-v2/shared/reception.js'){
    // Shared source supports Developing's test slot; Production cannot activate it.
    const marker=/^const DEVELOP_TEST_ONLY=[^\n]+;$/m;
    if(!marker.test(text))throw Error('Reception test-slot declaration changed; review Production specialization');
    text=text.replace(marker,'const PRODUCTION_TEST_DISABLED=false;');
    text=text.replaceAll('DEVELOP_TEST_ONLY','PRODUCTION_TEST_DISABLED');
    text=text.replace(/Developingテスト/g,'テスト');
  }
  return text.trim();
}
const bundleScripts=list=>"/* Generated by miniapp-v2/build-production.mjs; edit the listed source modules. */\n"+list.map(p=>"\n;/* "+p+" */\n"+browserSource(p)+"\n").join("");
const bundleStyles=list=>"/* Generated by miniapp-v2/build-production.mjs; source order is significant. */\n"+list.map(p=>{
  let text=read(p);
  if(/@import\b/i.test(text))throw Error("CSS imports must be bundled explicitly: "+p);
  text=text.replace(/url\(\s*(['"]?)([^)'"\s]+)\1\s*\)/g,(all,quote,url)=>{
    if(/^(?:[a-z]+:|\/|#)/i.test(url))return all;
    return "url("+quote+relative(resolve(root,dir),resolve(root,dirname(p))).split("\\").join("/")+"/"+url+quote+")";
  });
  return "\n/* "+p+" */\n"+text.trim()+"\n";
}).join("");
const routeScripts=sources.routeScripts||[];
const routeStyles=sources.routeStyles||[];
const routeJs=bundleScripts(routeScripts);
const routeCss=bundleStyles(routeStyles);
const routeLoader=`/* Load page-only code after the user leaves HOME. */
(()=>{'use strict';
let pending=null;
window.ASOBOON_V2_ENSURE_ROUTE_ASSETS=()=>{
 if(window.ASOBOON_V2_ROUTE_ASSETS_READY)return Promise.resolve();
 if(pending)return pending;
 pending=new Promise((resolve,reject)=>{
  let cssDone=false,jsDone=false,failed=false;
  const finish=()=>{if(!failed&&cssDone&&jsDone)resolve()};
  const fail=e=>{if(failed)return;failed=true;pending=null;reject(e||Error('ROUTE_ASSETS_LOAD_FAILED'))};
  const base=window.ASOBOON_V2_ENV?.assetBase||location.href;
  const link=document.createElement('link');link.rel='stylesheet';link.href=new URL('production-routes.css?v=${hash(routeCss)}',base).href;link.onload=()=>{cssDone=true;finish()};link.onerror=()=>fail(Error('ROUTE_CSS_LOAD_FAILED'));document.head.appendChild(link);
  const script=document.createElement('script');script.src=new URL('production-routes.js?v=${hash(routeJs)}',base).href;script.async=true;script.onload=()=>{jsDone=true;finish()};script.onerror=()=>fail(Error('ROUTE_JS_LOAD_FAILED'));document.head.appendChild(script);
 });
 return pending;
};
})();
`;
const js=routeLoader+bundleScripts(sources.scripts);
const css=bundleStyles(sources.styles);
output(`${dir}/production-app.js`,js);
output(`${dir}/production-app.css`,css);
output(`${dir}/production-routes.js`,routeJs);
output(`${dir}/production-routes.css`,routeCss);

const loader=`/* Generated by miniapp-v2/build-production.mjs. */
(()=>{'use strict';
if(window.ASOBOON_PRODUCTION_SHELL!==true||window.ASOBOON_ASOQUEST_HANDOFF)return;
const root=document.getElementById('app');if(!root)return;
document.body.dataset.asoboonApp='miniapp-v2';document.body.dataset.environment='production';
root.style.display='block';
if(!root.querySelector('.asoboon-boot'))root.innerHTML='<div class="asoboon-boot" role="status">ASOBooNを読み込み中…</div>';
const link=document.createElement('link');link.rel='stylesheet';link.href='./miniapp-v2/production/production-app.css?v=${hash(css)}';document.head.appendChild(link);
// async=false preserves execution order while all three downloads run concurrently.
const scripts=['https://static.line-scdn.net/liff/edge/2/sdk.js','./miniapp-v2/production/env-facility.js?v=${envHash(`${dir}/env-facility.js`)}','./miniapp-v2/production/production-app.js?v=${hash(js)}'];
for(const src of scripts){const s=document.createElement('script');s.src=src;s.async=false;s.onerror=()=>{
  if(src.startsWith('https:'))return; // The app already handles an unavailable LIFF SDK.
  root.innerHTML='<section style="padding:24px;font-family:system-ui,sans-serif"><h1>読み込みに失敗しました</h1><p>もう一度開き直してください。</p></section>';
};document.head.appendChild(s)}
})();
`;
output(`${dir}/production-shell-loader.js`,loader);
let home=read('home.html').replace(/production-shell-loader\.js\?v=[^'"\s]+/g,`production-shell-loader.js?v=${hash(loader)}`);
output('home.html',home);

